<script>
    const serviceCards = document.querySelectorAll(".service-card");

    const desktopDetailBox = document.getElementById("desktopDetailBox");
    const desktopTitle = document.getElementById("desktopDetailTitle");
    const desktopDescription = document.getElementById("desktopDetailDescription");

    serviceCards.forEach((card) => {

        card.addEventListener("click", () => {

            const isMobile = window.innerWidth <= 991;
            const isAlreadyActive = card.classList.contains("active");

            // remove active from all cards
            serviceCards.forEach((item) => {
                item.classList.remove("active");
            });

            // remove all mobile detail boxes
            document.querySelectorAll(".mobile-detail-wrapper").forEach((box) => {
                box.remove();
            });

            // hide desktop detail box
            desktopDetailBox.classList.remove("active");

            // toggle close if same card clicked
            if (isAlreadyActive) {
                return;
            }

            // activate current card
            card.classList.add("active");

            // get content
            const title = card.dataset.title;
            const description = card.dataset.description;

            /* =========================
               MOBILE VIEW
            ========================= */

            if (isMobile) {

                const wrapper = document.createElement("div");

                wrapper.className = "col-12 mobile-detail-wrapper";

                wrapper.innerHTML = `
    <div class="service-detail-box mobile-detail-box active">
      <h3>${title}</h3>
      <p>${description}</p>
    </div>
  `;

                const parentCol = card.closest(".col");

                // insert directly after clicked column
                parentCol.after(wrapper);

            }

            /* =========================
               DESKTOP VIEW
            ========================= */
            else {

                desktopTitle.textContent = title;
                desktopDescription.textContent = description;

                desktopDetailBox.classList.add("active");

            }

        });

    });
</script>

