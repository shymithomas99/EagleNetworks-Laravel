        // ===================================
        // BAR REJECT
        // ===================================

        if (rejectBarBtn) {
            rejectBarBtn.addEventListener("click", function() {

                localStorage.setItem("cookieConsent", JSON.stringify({
                    analytics: false
                }));

                cookieBar.style.display = "none";
            });
        }

        // ===================================
        // MODAL ACCEPT
        // ===================================

        if (acceptBtn) {
            acceptBtn.addEventListener("click", function() {

